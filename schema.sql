-- Application data lives outside the public/Data API schema.
CREATE SCHEMA IF NOT EXISTS mooboong;
SET search_path TO mooboong, pg_catalog;
    CREATE TABLE IF NOT EXISTS members (
      id TEXT PRIMARY KEY,
      name TEXT NOT NULL,
      password_hash TEXT NOT NULL,
      session TEXT NOT NULL DEFAULT '',
      generation TEXT NOT NULL DEFAULT '',
      phone TEXT NOT NULL DEFAULT '',
      admin INTEGER NOT NULL DEFAULT 0 CHECK(admin IN (0,1)),
      must_change_password INTEGER NOT NULL DEFAULT 1 CHECK(must_change_password IN (0,1)),
      created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
      updated_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
    );
    CREATE TABLE IF NOT EXISTS teams (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL UNIQUE,
      created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
      updated_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
    );
    CREATE TABLE IF NOT EXISTS team_members (
      team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
      slot TEXT NOT NULL CHECK(slot IN ('vocal','guitar1','guitar2','bass','drums','keyboard')),
      member_id TEXT NOT NULL REFERENCES members(id),
      PRIMARY KEY (team_id,slot)
    );
    CREATE TABLE IF NOT EXISTS sessions (
      token_hash TEXT PRIMARY KEY,
      member_id TEXT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
      expires_at BIGINT NOT NULL,
      created_at BIGINT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS bookings (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      member_id TEXT NOT NULL REFERENCES members(id),
      team_id INTEGER REFERENCES teams(id),
      type TEXT NOT NULL CHECK(type IN ('personal','team')),
      date TEXT NOT NULL,
      start_min INTEGER NOT NULL,
      end_min INTEGER NOT NULL,
      created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
      CHECK(end_min > start_min),
      CHECK((type='personal' AND team_id IS NULL) OR (type='team' AND team_id IS NOT NULL))
    );
    CREATE INDEX IF NOT EXISTS bookings_date ON bookings(date,start_min,end_min);
    CREATE TABLE IF NOT EXISTS events (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title TEXT NOT NULL,
      description TEXT NOT NULL DEFAULT '',
      date TEXT NOT NULL,
      start_min INTEGER NOT NULL CHECK(start_min >= 480 AND start_min % 30 = 0),
      end_min INTEGER NOT NULL CHECK(end_min <= 1440 AND end_min % 30 = 0),
      created_by TEXT NOT NULL REFERENCES members(id),
      CHECK(end_min > start_min)
    );
    CREATE INDEX IF NOT EXISTS events_date ON events(date,start_min,end_min);
    CREATE TABLE IF NOT EXISTS posts (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      kind TEXT NOT NULL CHECK(kind IN ('notice','wiki')),
      title TEXT NOT NULL,
      body TEXT NOT NULL,
      category TEXT NOT NULL DEFAULT '',
      pinned INTEGER NOT NULL DEFAULT 0 CHECK(pinned IN (0,1)),
      author_id TEXT NOT NULL REFERENCES members(id),
      created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
      updated_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
    );
    CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY,value TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS audit_log (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      actor_id TEXT,
      action TEXT NOT NULL,
      details TEXT NOT NULL DEFAULT '{}',
      created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
    );
    CREATE TABLE IF NOT EXISTS attachments (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
      name TEXT NOT NULL, mime TEXT NOT NULL, content BYTEA NOT NULL
    );
    CREATE TABLE IF NOT EXISTS wiki_assets (
      post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
      path TEXT NOT NULL, mime TEXT NOT NULL, content BYTEA NOT NULL, PRIMARY KEY(post_id,path)
    );

